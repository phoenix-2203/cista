/**
 * Compiles CistaVerifier (and the test mocks) with solc 0.8.28 and writes:
 *   src/artifact.ts        ABI + bytecode of CistaVerifier, used by the deploy script and the web app
 *   test/artifacts.json    every contract, for the tests
 * Run: pnpm --filter @cista/contracts build
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const solc = createRequire(import.meta.url)("solc") as { compile(input: string): string; version(): string };
const input = {
  language: "Solidity",
  sources: {
    "CistaVerifier.sol": { content: readFileSync("contracts/CistaVerifier.sol", "utf8") },
    "Mocks.sol": { content: readFileSync("test/Mocks.sol", "utf8") },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

const pick = (file: string, name: string) => {
  const c = out.contracts[file][name];
  return { abi: c.abi, bytecode: `0x${c.evm.bytecode.object}`, deployed: `0x${c.evm.deployedBytecode.object}` };
};
const verifier = pick("CistaVerifier.sol", "CistaVerifier");
mkdirSync("src", { recursive: true });
writeFileSync(
  "src/artifact.ts",
  `// Generated by scripts/build.ts from contracts/CistaVerifier.sol (solc ${solc.version()}). Do not edit.\n` +
    `export const CISTA_VERIFIER_ABI = ${JSON.stringify(verifier.abi, null, 2)} as const;\n\n` +
    `export const CISTA_VERIFIER_BYTECODE = "${verifier.bytecode}" as const;\n`,
);
writeFileSync(
  "test/artifacts.json",
  JSON.stringify({ CistaVerifier: verifier, MockPqcVerify: pick("Mocks.sol", "MockPqcVerify"), MockPqcKeyStatus: pick("Mocks.sol", "MockPqcKeyStatus") }),
);
console.log(`compiled CistaVerifier with solc ${solc.version()}: ${(verifier.deployed.length - 2) / 2} bytes deployed`);
